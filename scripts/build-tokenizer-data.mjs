// Build `src/client/data/tokenizer-data.ts` from a DeepSeek tokenizer.json:
// extracts the BPE merge table as (leftId, rightId) varint pairs (left/right
// in the merged symbol-id space: 0..255 = raw bytes, 256+i = merge i's
// output) and emits them as a base64 constant so the browser client bundle
// stays self-contained. The GPT-2 byte→char mapping is regenerated from its
// construction rule (checked into code, not shipped); the runtime decodes the
// blob with `atob` only — no DecompressionStream/jsdom dependency (gzip saves
// only ~8% on this blob, not worth the stream-API surface).
//
// Usage: node scripts/build-tokenizer-data.mjs <path-to-tokenizer.json>
import { readFileSync, writeFileSync } from 'node:fs'

const [, , src] = process.argv
if (!src) {
  console.error('usage: node scripts/build-tokenizer-data.mjs <tokenizer.json>')
  process.exit(1)
}

const doc = JSON.parse(readFileSync(src, 'utf8'))
const merges = doc.model?.merges
if (!Array.isArray(merges)) throw new Error('tokenizer.json has no model.merges')

// GPT-2 byte encoder (bytes_to_unicode): printable ASCII (33-126),
// 0xA1-0xAC and 0xAE-0xFF map to themselves; the remaining 68 bytes map to
// U+0100.. sequentially. Verified against the shipped vocab (all 256 bytes
// present).
const printable = new Set([
  ...Array.from({ length: 126 - 33 + 1 }, (_, i) => 33 + i),
  ...Array.from({ length: 172 - 161 + 1 }, (_, i) => 161 + i),
  ...Array.from({ length: 255 - 174 + 1 }, (_, i) => 174 + i),
])
const byteToChar = new Map()
let extra = 0
for (let b = 0; b < 256; b++) {
  if (printable.has(b)) byteToChar.set(b, b)
  else byteToChar.set(b, 256 + extra++)
}
const charToByte = new Map([...byteToChar].map(([b, c]) => [c, b]))

/** Bytes → latin1 string key (one byte per char, lossless). */
function keyOf(bytes) {
  return Buffer.from(bytes).toString('latin1')
}

// symbol id space: 0..255 raw byte ids; 256+i for merge i (in order).
const symbolOf = new Map()
for (let b = 0; b < 256; b++) symbolOf.set(keyOf([b]), b)

function bytesFromToken(token) {
  const out = []
  for (const ch of token) {
    const b = charToByte.get(ch.codePointAt(0))
    if (b === undefined) {
      throw new Error(`merge token is not a byte-mapped character: ${JSON.stringify(token)}`)
    }
    out.push(b)
  }
  return out
}

// First pass: resolve every merge pair to symbol ids, verifying left/right are
// already-defined symbols (BPE training invariant: merge i's sides have id < 256+i).
const pairs = new Array(merges.length)
for (let i = 0; i < merges.length; i++) {
  const m = merges[i]
  const sp = m.indexOf(' ')
  if (sp <= 0 || sp >= m.length - 1) throw new Error(`bad merge entry ${i}: ${JSON.stringify(m)}`)
  const leftStr = m.slice(0, sp)
  const rightStr = m.slice(sp + 1)
  const leftKey = keyOf(bytesFromToken(leftStr))
  const rightKey = keyOf(bytesFromToken(rightStr))
  const leftId = symbolOf.get(leftKey)
  const rightId = symbolOf.get(rightKey)
  if (leftId === undefined) throw new Error(`merge ${i}: unknown left symbol ${JSON.stringify(leftStr)}`)
  if (rightId === undefined) throw new Error(`merge ${i}: unknown right symbol ${JSON.stringify(rightStr)}`)
  pairs[i] = [leftId, rightId]
  symbolOf.set(keyOf([...bytesFromToken(leftStr), ...bytesFromToken(rightStr)]), 256 + i)
}

// varint (big-endian base-128, 1-3 bytes since ids < 2^17).
function pushVarint(out, v) {
  const bytes = []
  do {
    bytes.push(v & 0x7f)
    v >>>= 7
  } while (v > 0)
  for (let i = bytes.length - 1; i >= 0; i--) {
    out.push(i > 0 ? bytes[i] | 0x80 : bytes[i])
  }
}

const blob = []
for (const [l, r] of pairs) {
  pushVarint(blob, l)
  pushVarint(blob, r)
}
const b64 = Buffer.from(blob).toString('base64')

const out = `// AUTO-GENERATED by scripts/build-tokenizer-data.mjs — do not edit by hand.
// Regenerate with:
//   node scripts/build-tokenizer-data.mjs <path-to-deepseek-tokenizer.json>
// Blob layout: varint pairs [leftId, rightId] in merge rank order. Symbol ids:
// 0..255 are raw UTF-8 byte values; 256+i is the output symbol of merge i.
export const TOKENIZER_DATA_VERSION = 1
export const TOKENIZER_MERGES = ${merges.length}
export const TOKENIZER_MERGES_BASE64: string =
  '${b64}'
`

const dest = new URL('../src/client/data/tokenizer-data.ts', import.meta.url)
writeFileSync(dest, out)
console.log(`written ${dest.pathname} — raw ${blob.length}B, base64 ${b64.length} chars`)
